const toBoolean = (value, defaultValue = false) => {
  if (value === undefined) return defaultValue
  if (typeof value === 'boolean') return value
  return String(value).toLowerCase() === 'true'
}

const toNumber = (value, defaultValue) => {
  const parsed = Number.parseInt(String(value), 10)
  return Number.isNaN(parsed) ? defaultValue : parsed
}

const paginate = (list, page = 0, size = 10000) => {
  const safePage = Math.max(0, toNumber(page, 0))
  const safeSize = Math.max(1, toNumber(size, 10000))
  const start = safePage * safeSize
  const end = start + safeSize
  return {
    content: list.slice(start, end),
    page: safePage,
    size: safeSize,
    totalElements: list.length,
  }
}

const withItemFilter = (items, { roadmapType, includeInactive }) => {
  return items.filter((item) => {
    const roadmapMatched = !roadmapType || item.roadmapType === roadmapType
    const activeMatched = includeInactive ? true : item.isActive !== false
    return roadmapMatched && activeMatched
  })
}

const withTechFilter = (techs, { roadmapType, includeInactive }) => {
  return techs.filter((item) => {
    const roadmapMatched = !roadmapType || item.roadmapType === roadmapType
    const activeMatched = includeInactive ? true : item.isActive !== false
    return roadmapMatched && activeMatched
  })
}

export const hasWorkspaceRoadmapItem = (itemId) => {
  return workspaceRoadmapItems.some((item) => item.id === itemId)
}

export const getWorkspaceRoadmapItems = (query = {}) => {
  const includeInactive = toBoolean(query.includeInactive, false)
  const filtered = withItemFilter(workspaceRoadmapItems, {
    roadmapType: query.roadmapType,
    includeInactive,
  })
  return paginate(filtered, query.page, query.size)
}

export const getWorkspaceRoadmapTechs = (itemId, query = {}) => {
  const includeInactive = toBoolean(query.includeInactive, false)
  const source = workspaceRoadmapTechsByItem[itemId] || []
  const filtered = withTechFilter(source, {
    roadmapType: query.roadmapType,
    includeInactive,
  })
  return paginate(filtered, query.page, query.size)
}

export const getWorkspaceRoadmapTrm = (itemId, query = {}) => {
  const techPage = getWorkspaceRoadmapTechs(itemId, query)
  return {
    ...techPage,
    content: techPage.content.map((tech) => ({
      ...tech,
      relationType: 'TRM',
    })),
  }
}
